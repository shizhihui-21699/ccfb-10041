/**
 * Demo corpus: 18 protected documents across docx / xlsx / pdf / txt.
 *
 * Every block below becomes exactly one segment in the protected document
 * (the parsers emit one block per paragraph / table row / text line), so
 * sample ground-truth labels can address segments by array index.
 *
 * All names, numbers and companies are fictional.
 */

export interface CorpusBlock {
  text: string;
  kind?: 'heading' | 'paragraph' | 'row' | 'line';
  /** xlsx sheet name */
  sheet?: string;
}

export interface CorpusDoc {
  id: string;
  title: string;
  owner: string;
  classification: '绝密' | '机密' | '内部';
  format: 'docx' | 'xlsx' | 'pdf' | 'txt';
  /**
   * Customer lists are vault-only: content is converted to salted hashes and
   * never enters the fingerprint library.
   */
  piiOnly?: boolean;
  /** Sheet names for xlsx in order; blocks carry sheet names. */
  sheets?: string[];
  blocks: CorpusBlock[];
}

const p = (text: string): CorpusBlock => ({ text, kind: 'paragraph' });
const row = (text: string, sheet: string): CorpusBlock => ({ text, kind: 'row', sheet });

